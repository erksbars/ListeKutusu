import { expect, test } from "@playwright/test";
import { PrismaClient } from "@prisma/client";
import { randomUUID } from "node:crypto";

test("community URL navigation, browser history, spoiler and in-page drafts", async ({ page, context, baseURL }) => {
  test.skip(process.env.COMMUNITY_E2E !== "1", "Local navigation integration is opt-in.");
  if (!baseURL || new URL(baseURL).hostname !== "127.0.0.1") throw new Error("Local test only");
  test.setTimeout(150_000); page.setDefaultTimeout(20_000);
  const db = new PrismaClient(), suffix = randomUUID(), email = `navigation-${suffix}@example.test`;
  const errors: string[] = []; page.on("pageerror", error => errors.push(error.message));
  let userId: string | undefined;
  try {
    const registration = await context.request.post("/api/accounts", { headers: { Origin: baseURL, "X-Forwarded-For": `192.0.2.${1 + parseInt(suffix.slice(0, 2), 16) % 254}` }, data: { email, password: `Test-${suffix}-42`, ownerName: "Gezinme Denemesi", playlistName: "Geçici test" } });
    expect(registration.status()).toBe(200);
    userId = (await db.userList.findUniqueOrThrow({ where: { email }, select: { id: true } })).id;
    const response = await context.request.post("/api/communities", { headers: { Origin: baseURL }, data: { name: "Gezinme Deneme Topluluğu", category: "interest", description: "Masaüstü gezinme ve taslak için geçici topluluk.", rules: "Gerçek bir topluluk değildir; yalnız test verisidir." } });
    expect(response.status()).toBe(201); const { slug } = await response.json();
    const community = await db.community.findUniqueOrThrow({ where: { slug } }), firstPostId = `navigation-post-${suffix}`;
    const clock = Date.now();
    await db.communityPost.createMany({ data: Array.from({ length: 21 }, (_, index) => ({ id: index === 0 ? firstPostId : `navigation-${suffix}-${index}`, communityId: community.id, authorId: userId!, title: index === 0 ? "Gezinme spoiler incelemesi" : `Gezinme sohbeti ${index}`, body: index === 0 ? "Gizli inceleme sonu yalnız açık tercihle görünür." : "Yalnız geçici gezinme testi sohbetidir.", createdAt: new Date(clock + index * 1000), ...(index === 0 ? { type: "review", reviewKind: "movie", subjectTitle: "Kurgusal film", rating: 8, spoiler: true } : {}) })) });
    await db.communityComment.createMany({ data: Array.from({ length: 41 }, (_, index) => ({ postId: firstPostId, authorId: userId!, body: `Gezinme yorumu ${index}`, createdAt: new Date(clock + index * 1000) })) });
    await db.communityEvent.createMany({ data: Array.from({ length: 21 }, (_, index) => ({ id: `navigation-event-${suffix}-${index}`, communityId: community.id, organizerId: userId!, title: `İptal edilmiş gezinme etkinliği ${index}`, description: "Yalnız geçici gezinme testi etkinliğidir.", status: "cancelled", startsAt: new Date(clock + 7 * 86400_000 + index * 60_000), city: "İstanbul", venue: "Kurgusal kamusal test alanı" })) });
    await page.addInitScript(() => localStorage.setItem("listekutusu-theme", "dark"));
    await page.goto(`/communities/${slug}`);
    const types = page.getByRole("group", { name: "Akış içerik türü", exact: true });
    await expect(page.locator("[data-feed-id]")).toHaveCount(10);
    await page.locator("summary").filter({ hasText: /^Sohbet veya inceleme paylaş$/ }).click();
    const postDraft = page.getByRole("textbox", { name: "Paylaşım başlığı", exact: true });
    await expect(postDraft).toBeEnabled(); await postDraft.fill("Kaybolmaması gereken sohbet taslağı");
    await page.getByRole("button", { name: "Sonraki paylaşımlar", exact: true }).click();
    await expect(page).toHaveURL(/page=2/);
    expect(new URL(page.url()).searchParams.get("cursor")).toBeTruthy();
    await expect(page.locator("[data-feed-id]")).toHaveCount(10);
    await expect(postDraft).toHaveValue("Kaybolmaması gereken sohbet taslağı");
    await types.getByRole("button", { name: "İncelemeler", exact: true }).click();
    await expect(page).not.toHaveURL(/page=2/);
    expect(new URL(page.url()).searchParams.has("cursor")).toBe(false);
    const reviewCard = page.locator(`[data-feed-id="post:${firstPostId}"]`), openReview = reviewCard.locator(".feed-post-permalink");
    const reviewSource = page.url();
    await reviewCard.getByRole("button", { name: "Spoiler içeren metni göster", exact: true }).click();
    await expect(reviewCard.getByText("Gizli inceleme sonu yalnız açık tercihle görünür.", { exact: true })).toBeVisible();
    await expect(page).toHaveURL(reviewSource);
    // A permalink is an explicit navigation: cancelling it must keep the create draft.
    await openReview.click();
    const exitDialog = page.getByRole("dialog", { name: "Değişiklikler kaydedilmedi", exact: true });
    await expect(exitDialog).toBeVisible(); await page.keyboard.press("Escape");
    await expect(page).toHaveURL(reviewSource); await expect(postDraft).toHaveValue("Kaybolmaması gereken sohbet taslağı");
    await postDraft.fill("");
    await openReview.click(); await expect(page).toHaveURL(new RegExp(`post=${firstPostId}`));
    await expect(page.getByRole("link", { name: "Paylaşım bağlantısı ↗", exact: true })).toHaveAttribute("href", `/communities/${slug}?post=${firstPostId}`);
    await page.getByRole("button", { name: "Akışa dön", exact: true }).click();
    await expect(page).toHaveURL(reviewSource); await expect(postDraft).toHaveValue("");
    await openReview.click(); await page.getByRole("button", { name: "İncelemeyi ve yorumları göster", exact: true }).click();
    await page.getByRole("button", { name: "Sonraki yorumlar", exact: true }).click(); await expect(page).toHaveURL(/commentsPage=2/);
    await expect(page.getByText("Gezinme yorumu 40", { exact: true })).toBeVisible();
    await page.goBack(); await expect(page).not.toHaveURL(/commentsPage=2/);
    await page.goForward(); await expect(page).toHaveURL(/commentsPage=2/);
    await page.reload();
    await expect(page.getByRole("button", { name: "İncelemeyi ve yorumları göster", exact: true })).toBeVisible();
    await expect(page.getByText("Gizli inceleme sonu yalnız açık tercihle görünür.", { exact: true })).toHaveCount(0);
    await page.getByRole("button", { name: "İncelemeyi ve yorumları göster", exact: true }).click();
    await expect(page.getByText("Gezinme yorumu 40", { exact: true })).toBeVisible();
    await page.getByRole("link", { name: "Paylaşım bağlantısı ↗", exact: true }).click();
    await expect(page).not.toHaveURL(/commentsPage=2/);
    await expect(page.getByRole("button", { name: "Sonraki yorumlar", exact: true })).toBeVisible();
    await page.getByRole("button", { name: "Akışa dön", exact: true }).click();
    await types.getByRole("button", { name: "Etkinlikler", exact: true }).click();
    await expect(page).toHaveURL(/section=events/);
    await page.locator("summary").filter({ hasText: /^Etkinlik oluştur$/ }).click();
    const eventDraft = page.getByRole("textbox", { name: "Etkinlik başlığı", exact: true });
    await expect(eventDraft).toBeEnabled(); await eventDraft.fill("Korunacak etkinlik taslağı");
    const eventFilter = page.getByRole("combobox", { name: "Etkinlik zamanı", exact: true });
    await eventFilter.selectOption("cancelled");
    for (let next = 2; next <= 3; next++) { await page.getByRole("button", { name: "Sonraki paylaşımlar", exact: true }).click(); await expect(page).toHaveURL(new RegExp(`eventPage=${next}`)); }
    expect(new URL(page.url()).searchParams.get("cursor")).toBeTruthy();
    const eventCards = page.locator('[data-feed-kind="event"]'), eventOpen = eventCards.locator(".feed-post-permalink");
    await expect(eventCards).toHaveCount(1);
    await eventOpen.click(); await expect(exitDialog).toBeVisible(); await page.keyboard.press("Escape");
    await expect(eventDraft).toHaveValue("Korunacak etkinlik taslağı");
    await eventDraft.fill("");
    await eventOpen.click(); await expect(page).toHaveURL(/event=navigation-event-/);
    await page.getByRole("button", { name: "Etkinlik listesine dön", exact: true }).click();
    await eventDraft.fill("Korunacak etkinlik taslağı");
    await types.getByRole("button", { name: "Tümü", exact: true }).click();
    await types.getByRole("button", { name: "Etkinlikler", exact: true }).click();
    await expect(eventDraft).toHaveValue("Korunacak etkinlik taslağı");
    await eventDraft.fill("");
    await expect(eventFilter).toHaveValue("cancelled");
    for (let next = 2; next <= 3; next++) { await page.getByRole("button", { name: "Sonraki paylaşımlar", exact: true }).click(); await expect(page).toHaveURL(new RegExp(`eventPage=${next}`)); }
    await expect(eventCards).toHaveCount(1);
    await expect(eventCards.getByText("Tercihin: Henüz belirtilmedi", { exact: true })).toBeVisible();
    let fail = true;
    await page.route(`**/api/communities/${slug}/events/navigation-event-*`, route => { if (!fail) return route.continue(); fail = false; return route.fulfill({ status: 503, json: { error: "Geçici etkinlik okuma hatası" } }); });
    await expect(eventOpen).toBeEnabled(); await eventOpen.click();
    await expect(page.getByRole("alert").filter({ hasText: "Geçici etkinlik okuma hatası" })).toBeVisible();
    await page.getByRole("button", { name: "Etkinliği yeniden yükle", exact: true }).click();
    await expect(page.getByRole("link", { name: "Etkinlik bağlantısı ↗", exact: true })).toBeVisible();
    await page.reload();
    await expect(page.getByRole("link", { name: "Etkinlik bağlantısı ↗", exact: true })).toBeVisible();
    await page.getByRole("button", { name: "Etkinlik listesine dön", exact: true }).click();
    await expect(eventFilter).toHaveValue("cancelled");
    await expect(eventOpen).toHaveCount(1); await expect(page).toHaveURL(/eventPage=3/);
    expect(new URL(page.url()).searchParams.get("cursor")).toBeTruthy();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.evaluate(() => window.scrollTo({ top: 0, behavior: "instant" }));
    await page.screenshot({ path: "test-results/browser/community-navigation-desktop.png", fullPage: false, animations: "disabled" });
    expect(errors).toEqual([]);
  } finally {
    const user = userId ?? (await db.userList.findUnique({ where: { email }, select: { id: true } }))?.id;
    if (user) { await db.community.deleteMany({ where: { ownerId: user } }); await db.userList.deleteMany({ where: { id: user } }); }
    await db.$disconnect();
  }
});
